#!/usr/bin/env python3
"""
Single source of truth for every number quoted in the manuscript.

Reads the CLEAN result files and emits:
    results/paper_tables_<tag>.md    — ready-to-paste Markdown tables
    results/paper_numbers_<tag>.json — flat {key: value} dict for in-text numbers

Rule for the rewrite: if a number is not in paper_numbers_<tag>.json, it does
not go into the paper. This is what prevents the Table-3-vs-Table-10 style
contradictions flagged by Reviewer 3.

Usage:
    python scripts/make_paper_tables.py            # tag = clean
    python scripts/make_paper_tables.py --tag clean_smoke
"""

from __future__ import annotations

import argparse
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

DISPLAY = {
    "HiT-IDS (Cascade)": "HiT-IDS (cascade)",
    "random_forest": "Random Forest",
    "xgboost": "XGBoost",
    "bilstm": "BiLSTM",
    "vanilla_transformer": "Vanilla Transformer",
    "cnn_1d": "1D-CNN",
    "Deep-IDS": "Deep-IDS (LSTM)",
}
MAIN_ORDER = ["HiT-IDS (Cascade)", "random_forest", "xgboost", "bilstm",
              "vanilla_transformer", "Deep-IDS", "cnn_1d"]


def load(path):
    if os.path.exists(path):
        with open(path) as f:
            return json.load(f)
    return None


def pm(m, s, nd=4):
    return f"{m:.{nd}f} ± {s:.{nd}f}"


def md_table(header, rows, align=None):
    align = align or ["---"] * len(header)
    out = ["| " + " | ".join(header) + " |", "| " + " | ".join(align) + " |"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", default="clean")
    ap.add_argument("--tables-dir", default="results/tables")
    args = ap.parse_args()
    tag = args.tag

    cv = load(os.path.join(args.tables_dir, f"cv_evaluation_{tag}.json"))
    abl = load(os.path.join(args.tables_dir, f"ablation_results_{tag}.json")) or \
        load(os.path.join(args.tables_dir, f"ablation_results_{tag.replace('_thr', '')}.json"))
    counts = load("data/processed/clean_full_class_counts.json")
    base = tag.replace("_thr", "")
    deepids = load(f"revision_results/results_deepids_{base}.json") or \
        load("revision_results/results_deepids_clean.json")
    unsw = load("results/unsw_nb15/tables/unsw_binary_cv_results.json")

    md, num = [], {"_tag": tag}
    md.append(f"# HiT-IDS — paper tables (protocol tag: `{tag}`)\n")
    md.append("All CIC-IDS2017 numbers below come from REAL test-fold rows only "
              "(RobustScaler + SMOTE fitted inside each training fold). "
              "Generated by `scripts/make_paper_tables.py`; do not edit by hand.\n")

    # ── Dataset table ────────────────────────────────────────────────────
    if counts:
        md.append("## Table D1. CIC-IDS2017 after cleaning (real rows, no resampling)\n")
        c13 = counts["counts_13_class_merged"]
        total = counts["total_rows"]
        rows = [(k, f"{v:,}", f"{100*v/total:.3f}%") for k, v in
                sorted(c13.items(), key=lambda kv: -kv[1])]
        rows.append(("**Total**", f"**{total:,}**", "100%"))
        md.append(md_table(["Class", "Count", "Share"], rows, ["---", "---:", "---:"]))
        c15 = counts["counts_15_class"]
        web = {k: v for k, v in c15.items() if k.startswith("Web Attack")}
        md.append("\nWeb Attack merges " +
                  ", ".join(f"{k.split(' - ')[-1]} ({v:,})" for k, v in web.items()) +
                  ". Cleaning: identifier columns dropped, inf→NaN rows dropped, exact duplicates removed.\n")
        num["dataset_total_real_rows"] = total
        for k, v in c13.items():
            num[f"dataset_count_{k}"] = v

    if cv:
        S = cv["summary"]
        K = cv["k_folds"]
        num["k_folds"] = K
        num["protocol"] = cv.get("protocol", {})

        # ── Fold composition ─────────────────────────────────────────────
        if cv.get("folds"):
            md.append(f"## Table D2. Test-fold composition ({K}-fold, real rows)\n")
            classes = cv["class_names"]
            header = ["Class"] + [f"Fold {f['fold']+1}" for f in cv["folds"]]
            rows = []
            for c in classes:
                rows.append([c] + [f"{f['test_class_counts'][c]:,}" for f in cv["folds"]])
            rows.append(["**Total**"] + [f"**{f['n_test_real']:,}**" for f in cv["folds"]])
            md.append(md_table(header, rows))
            f0 = cv["folds"][0]
            if "train_class_counts_after_smote" in f0:
                md.append("\nTraining fold after SMOTE + BENIGN cap (fold 1): " +
                          ", ".join(f"{k} {v:,}" for k, v in
                                    f0["train_class_counts_after_smote"].items()) + "\n")

        # ── Main comparison ──────────────────────────────────────────────
        md.append(f"## Table R1. {K}-fold stratified CV on CIC-IDS2017 (13 classes)\n")
        rows = []
        models = [m for m in MAIN_ORDER if m in S]
        if deepids and "mean_macro_f1" in deepids:
            models.insert(min(5, len(models)), "Deep-IDS")
        for m in models:
            if m == "Deep-IDS":
                d = deepids
                mf, sf = d["mean_macro_f1"], d["std_macro_f1"]
                rows.append([DISPLAY[m], pm(mf, sf), f"{d.get('mean_accuracy', np.nan):.4f}",
                             f"{d.get('mean_weighted_f1', np.nan):.4f}", "—"])
                num["cv_macro_f1_mean_Deep-IDS"] = mf
                continue
            s = S[m]
            auc = s.get("mean_macro_roc_auc_ovr")
            rows.append([DISPLAY.get(m, m), pm(s["mean_macro_f1"], s["std_macro_f1"]),
                         f"{s['mean_accuracy']:.4f}", f"{s['mean_weighted_f1']:.4f}",
                         f"{auc:.4f}" if auc is not None else "—"])
            num[f"cv_macro_f1_mean_{m}"] = s["mean_macro_f1"]
            num[f"cv_macro_f1_std_{m}"] = s["std_macro_f1"]
            num[f"cv_accuracy_{m}"] = s["mean_accuracy"]
            num[f"cv_weighted_f1_{m}"] = s["mean_weighted_f1"]
            if auc is not None:
                num[f"cv_macro_roc_auc_{m}"] = auc
        md.append(md_table(["Model", "Macro-F1 (mean ± std)", "Accuracy", "Weighted-F1",
                            "Macro ROC-AUC (OvR)"], rows))
        md.append("")

        # ── Statistical tests ────────────────────────────────────────────
        if cv.get("statistical_tests"):
            md.append("## Table R2. Paired tests, HiT-IDS vs. each baseline (macro-F1, per fold)\n")
            rows = []
            for bl, t in cv["statistical_tests"].items():
                rows.append([DISPLAY.get(bl, bl), f"{t['delta_mean']:+.4f}",
                             f"[{t['delta_ci'][0]:+.4f}, {t['delta_ci'][1]:+.4f}]",
                             f"{t['cohens_d']:.2f}", f"{t['p_value']:.4g}",
                             "yes" if t["significant"] else "no"])
                num[f"stat_delta_f1_vs_{bl}"] = t["delta_mean"]
                num[f"stat_p_vs_{bl}"] = t["p_value"]
                num[f"stat_d_vs_{bl}"] = t["cohens_d"]
            md.append(md_table(["Baseline", "ΔF1 (HiT − baseline)", "95% CI", "Cohen's d",
                                "p (one-sided paired t)", "p < 0.05"], rows))
            md.append("\nNote: with K = 5 folds, treat p-values as indicative; effect sizes and CIs carry the argument.\n")

        # ── Per-class for HiT-IDS ────────────────────────────────────────
        hit = S.get("HiT-IDS (Cascade)")
        if hit and hit.get("per_class"):
            md.append(f"## Table R3. Per-class results of HiT-IDS across {K} folds (real test rows)\n")
            rows = []
            for c, v in hit["per_class"].items():
                sup = v["support_per_fold"]
                rows.append([c, pm(v["precision_mean"], v["precision_std"], 3),
                             pm(v["recall_mean"], v["recall_std"], 3),
                             pm(v["f1_mean"], v["f1_std"], 3),
                             f"{int(np.sum(sup)):,} ({min(sup)}–{max(sup)}/fold)"])
                num[f"hit_perclass_f1_mean_{c}"] = v["f1_mean"]
                num[f"hit_perclass_f1_std_{c}"] = v["f1_std"]
                num[f"hit_perclass_support_total_{c}"] = int(np.sum(sup))
            md.append(md_table(["Class", "Precision", "Recall", "F1", "Support (total, per fold)"], rows))
            md.append("")

        # ── Per-class F1 across models ───────────────────────────────────
        md.append("## Table R4. Per-class F1 (mean over folds) — all models\n")
        header = ["Class"] + [DISPLAY.get(m, m) for m in models if m != "Deep-IDS" and m in S]
        rows = []
        for c in cv["class_names"]:
            r = [c]
            for m in models:
                if m == "Deep-IDS" or m not in S:
                    continue
                pc = S[m].get("per_class", {}).get(c)
                r.append(f"{pc['f1_mean']:.3f}" if pc else "—")
            rows.append(r)
        md.append(md_table(header, rows))
        md.append("")

        # ── Binary stage ─────────────────────────────────────────────────
        md.append("## Table R5. Attack-vs-benign view (derived from the 13-class predictions)\n")
        rows = []
        for m in models:
            if m == "Deep-IDS" or m not in S or "binary" not in S[m]:
                continue
            b = S[m]["binary"]
            g = lambda k: f"{b[k]['mean']:.4f} ± {b[k]['std']:.4f}" if k in b else "—"
            rows.append([DISPLAY.get(m, m), g("f1"), g("precision"), g("recall"), g("fpr"),
                         g("roc_auc"), g("pr_auc")])
            for k in b:
                num[f"binary_{k}_mean_{m}"] = b[k]["mean"]
        md.append(md_table(["Model", "F1", "Precision", "Recall (detection rate)",
                            "FPR", "ROC-AUC", "PR-AUC"], rows))
        md.append("")

        # ── Confusion matrix (summed) ────────────────────────────────────
        if hit and "confusion_matrix_sum" in hit:
            md.append(f"## Table R6. HiT-IDS confusion matrix summed over {K} folds (rows = true)\n")
            cm = np.array(hit["confusion_matrix_sum"])
            short = [c.replace("DoS ", "DoS-").replace(" ", "")[:9] for c in cv["class_names"]]
            header = ["True \\ Pred"] + short
            rows = [[short[i]] + [f"{int(x):,}" for x in cm[i]] for i in range(len(short))]
            md.append(md_table(header, rows))
            num["hit_cm_total"] = int(cm.sum())
            num["hit_cm_correct"] = int(np.trace(cm))
            num["hit_cm_errors"] = int(cm.sum() - np.trace(cm))
            md.append("")

    # ── Ablation ─────────────────────────────────────────────────────────
    if abl:
        md.append("## Table R7. Ablation (same clean protocol, all variants at Stage-1 threshold 0.5, macro-F1)\n")
        ref = abl.get("reference", {}).get("mean_macro_f1", np.nan)
        rows = [["—", "**Full HiT-IDS**", f"**{ref:.4f}**", "", "—"]]
        for k, v in abl.items():
            if not k.startswith("A"):
                continue
            rows.append([k, v["name"], f"{v['mean_macro_f1']:.4f}", f"{v['std_macro_f1']:.4f}",
                         f"{v['delta_f1']:+.4f}"])
            num[f"ablation_{k}_f1"] = v["mean_macro_f1"]
            num[f"ablation_{k}_delta"] = v["delta_f1"]
        md.append(md_table(["ID", "Variant", "Mean F1", "± Std", "ΔF1"], rows))
        md.append("")

    # ── UNSW-NB15 ────────────────────────────────────────────────────────
    if unsw:
        md.append("## Table R8. UNSW-NB15 binary, 5-fold CV (raw CSVs, fold-internal SMOTE)\n")
        rows = []
        for m in ["HiT-IDS", "random_forest", "xgboost", "bilstm", "vanilla_transformer"]:
            s = unsw["summary"].get(m)
            if not s:
                continue
            rows.append([DISPLAY.get(m, m), pm(s["mean_macro_f1"], s["std_macro_f1"]),
                         f"{s['mean_accuracy']:.4f}"])
            num[f"unsw_macro_f1_mean_{m}"] = s["mean_macro_f1"]
        md.append(md_table(["Model", "Macro-F1 (mean ± std)", "Accuracy"], rows))
        md.append("")

    # ── Deployment model (single split, XAI model) ───────────────────────
    dep = load("results/tables/deployment_eval.json")
    if dep:
        md.append("## Table X1. Deployment model (70/15/15 split) — the model used for all XAI analyses\n")
        rows = []
        for lab, name in (("argmax_0.5", "argmax (t = 0.5)"), ("calibrated", f"validation-calibrated (t* = {dep['stage1_threshold']:.3f})")):
            r = dep["test"][lab]
            rows.append([name, f"{r['macro_f1']:.4f}", f"{r['accuracy']:.4f}", f"{r['binary']['f1']:.4f}",
                         f"{r['binary']['recall']:.4f}", f"{100*r['binary']['fpr']:.3f}%",
                         f"{r['per_class']['Bot']['f1']:.3f}", f"{r['per_class']['Infiltration']['f1']:.3f}"])
        md.append(md_table(["Stage-1 rule", "Macro-F1", "Accuracy", "Binary F1", "Detection rate",
                            "FPR", "Bot F1", "Infiltration F1"], rows))
        md.append(f"\nTest rows: {dep['n_test']:,} (real). Threshold chosen on {dep['n_val']:,} real validation rows.\n")
        c = dep["test"]["calibrated"]
        num["deploy_threshold"] = dep["stage1_threshold"]
        num["deploy_macro_f1"] = c["macro_f1"]
        num["deploy_macro_f1_argmax"] = dep["test"]["argmax_0.5"]["macro_f1"]
        num["deploy_binary_f1"] = c["binary"]["f1"]
        num["deploy_fpr"] = c["binary"]["fpr"]
        for cl, v in c["per_class"].items():
            num[f"deploy_perclass_f1_{cl}"] = v["f1"]
        md.append("### Table X1b. Deployment model per-class (calibrated)\n")
        md.append(md_table(["Class", "Precision", "Recall", "F1", "Support"],
                           [[cl, f"{v['precision']:.3f}", f"{v['recall']:.3f}", f"{v['f1']:.3f}", f"{v['support']:,}"]
                            for cl, v in c["per_class"].items()]))
        md.append("")

    # ── XCS both ways ────────────────────────────────────────────────────
    xcs = load("results/tables/xcs_both_clean.json")
    if xcs:
        md.append(f"## Table X2. Attention–SHAP consistency (XCS), {xcs['protocol']['n_samples']} correctly classified attack rows\n")
        pretty = {"rollout_vs_shap_predclass": "rollout vs |SHAP| (predicted class)",
                  "rollout_vs_shap_meanclass": "rollout vs mean_c |SHAP_c|",
                  "attn_x_grad_vs_shap_predclass": "attention×|grad| vs |SHAP| (predicted class)",
                  "attn_x_grad_vs_shap_meanclass": "attention×|grad| vs mean_c |SHAP_c| (as submitted)",
                  "gradient_only_vs_shap_predclass": "|grad| alone vs |SHAP| (predicted class)",
                  "rollout_vs_attn_x_grad": "rollout vs attention×|grad|"}
        rows = []
        for k, v in xcs["pairs"].items():
            rows.append([pretty.get(k, k), f"{v['mean_rho']:.3f} ± {v['std_rho']:.3f}", f"{v['median_rho']:.3f}",
                         f"{v['pct_significant_p05']:.1f}%", f"{v['top5_overlap']:.3f}", f"{v['top10_overlap']:.3f}", f"{v['top15_overlap']:.3f}"])
            num[f"xcs_{k}_mean_rho"] = v["mean_rho"]
            num[f"xcs_{k}_top10"] = v["top10_overlap"]
        md.append(md_table(["Attribution pair", "Spearman ρ (mean ± std)", "median", "% p<0.05", "top-5", "top-10", "top-15"], rows))
        md.append("\nTop-10 global features — rollout: " + ", ".join(xcs["global_top10"]["rollout"]) +
                  "; SHAP: " + ", ".join(xcs["global_top10"]["shap_predclass"]) + "\n")
        md.append("Mean group importance (deployment model): " +
                  ", ".join(f"{g} {v:.3f}" for g, v in xcs["group_importance_mean"].items()) + "\n")

    # ── Fold stability of group importance ───────────────────────────────
    fgi = load(f"results/tables/fold_group_importance_{tag.replace('_thr','')}.json")
    if fgi:
        md.append(f"## Table X3. Group importance per attack type, mean ± std over {fgi['k_folds']} fold models\n")
        G = fgi["groups"]
        rows = []
        for cl in fgi["classes"]:
            m, s = fgi["per_class_mean"][cl], fgi["per_class_std"][cl]
            rows.append([cl] + [f"{m[g]:.3f} ± {s[g]:.3f}" for g in G] +
                        [fgi["dominant_group"][cl], f"{100*fgi['dominant_group_agreement_across_folds'][cl]:.0f}%"])
        md.append(md_table(["Attack", *[g.capitalize() for g in G], "Dominant", "Folds agreeing"], rows))
        sp = fgi["interfold_spearman_global72"]
        md.append(f"\nInter-fold Spearman ρ of the 72-feature global importance: mean {sp['mean']:.3f} "
                  f"(min {sp['min']:.3f}, max {sp['max']:.3f}).\n")
        num["foldstab_interfold_rho_mean"] = sp["mean"]
        num["foldstab_interfold_rho_min"] = sp["min"]

    # ── Error analysis ───────────────────────────────────────────────────
    ea = load("results/tables/error_analysis_clean.json")
    if ea:
        md.append("## Table X4. Largest error groups of the deployment model and their attention divergence\n")
        rows = []
        for gid, v in ea["error_groups"].items():
            d = v["group_attention_delta"]
            rows.append([v["desc"], f"{v['n']:,}", f"{v['confidence_mean']:.3f}"] +
                        [f"{d[g]:+.3f}" for g in d])
        md.append(md_table(["Error group", "n", "mean conf.", *[f"Δ {g}" for g in d]], rows))
        t = ea.get("totals", {})
        md.append(f"\nTotal misclassified: {t.get('misclassified', '?'):,} of {t.get('n', '?'):,}. "
                  f"Stage-1 benign false positives: {ea['stage1'].get('BENIGN_false_positive', {}).get('count', '?'):,}.\n")
        num["errors_total"] = t.get("misclassified")

    # ── Explanation latency ──────────────────────────────────────────────
    lat = load("results/tables/explanation_latency_clean.json")
    if lat:
        md.append(f"## Table X5. Explanation latency, one protocol (N={lat['protocol']['n_explain_samples']}, "
                  f"{lat['protocol']['repeats']} repeats, median), {lat['hardware'].get('gpu')}\n")
        rows = []
        for k, v in lat["results_ms_per_sample"].items():
            s = v.get("single_ms_per_sample", {}).get("median")
            b = v.get("batched_ms_per_sample", {}).get("median")
            rows.append([k, v.get("type", ""), f"{s:.3f}" if s is not None else "—", f"{b:.3f}" if b is not None else "—"])
            key = k.lower().replace(" ", "_").replace("-", "_").replace("(", "").replace(")", "")
            if s is not None:
                num[f"latency_single_ms_{key}"] = s
                num[f"latency_batched_ms_{key}"] = b
        md.append(md_table(["Method", "Type", "Single (batch=1) ms/sample", "Batched ms/sample"], rows))
        md.append("\nSpeed-up of attention rollout, same regime: " +
                  "; ".join(f"{k}: {v.get('single', float('nan')):.1f}× single / {v.get('batched', float('nan')):.0f}× batched"
                            for k, v in lat["speedup_of_attention_rollout_vs"].items()) + "\n")

    out_md = f"results/paper_tables_{tag}.md"
    out_js = f"results/paper_numbers_{tag}.json"
    with open(out_md, "w") as f:
        f.write("\n".join(md))
    with open(out_js, "w") as f:
        json.dump(num, f, indent=2, default=float)
    print(f"  wrote {out_md}\n  wrote {out_js}")
    if not cv:
        print("  [WARN] no cv_evaluation file found for this tag — run scripts/evaluate_cv.py first")


if __name__ == "__main__":
    main()
